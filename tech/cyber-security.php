<h1>Cyber Security</h1>
<p class="lead">Build the skills to protect accounts, applications, devices, and data. This learning path focuses on prevention, detection, and authorized practice.</p>

<div class="timeline">
<article class="card"><span class="time">1–2 weeks</span><h3>Security foundations</h3>
<p><b>Study:</b> Confidentiality, integrity and availability; risk; threat modeling; least privilege; and defense in depth.</p>
<p><b>Learn:</b> How to recognize common risks and explain practical ways to reduce them.</p></article>
<article class="card"><span class="time">2–3 weeks</span><h3>Networks and operating systems</h3>
<p><b>Study:</b> IP addresses, DNS, HTTP and HTTPS, basic network services, Linux and Windows permissions, and system updates.</p>
<p><b>Learn:</b> How devices communicate and how secure configuration helps protect them.</p></article>
<article class="card"><span class="time">1–2 weeks</span><h3>Account and data protection</h3>
<p><b>Study:</b> Password managers, multi-factor authentication, backups, encryption basics, privacy, and secure handling of secrets.</p>
<p><b>Learn:</b> How to protect accounts and reduce the impact of lost or exposed data.</p></article>
<article class="card"><span class="time">2–3 weeks</span><h3>Secure web development</h3>
<p><b>Study:</b> Input validation, output encoding, authentication and authorization, session safety, dependency updates, and secure error handling.</p>
<p><b>Learn:</b> How to build and review safer web applications using recognized security guidance.</p></article>
<article class="card"><span class="time">1–2 weeks</span><h3>Monitoring and incident response</h3>
<p><b>Study:</b> Useful application and system logs, alerting basics, incident reporting, containment, recovery, and lessons learned.</p>
<p><b>Learn:</b> How defenders identify unusual activity and respond through an organized process.</p></article>
<article class="card"><span class="time">Ongoing</span><h3>Practice safely and ethically</h3>
<p>Use intentionally vulnerable training applications or isolated labs that you own or have explicit permission to use. Keep practice systems separate from personal devices and real networks.</p>
<p><b>Learn:</b> Document findings clearly, recommend fixes, and verify changes only within the authorized scope.</p></article>
